function getDeviceLanguage() {
  const preferred = navigator.languages?.[0] ?? navigator.language ?? "en";
  return preferred.toLowerCase().startsWith("zh") ? "zh" : "en";
}

function readPreference() {
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return stored === "zh" || stored === "en" ? stored : "system";
}

function lookup(dictionary, key) {
  return key.split(".").reduce((value, segment) => value?.[segment], dictionary);
}

function interpolate(value, variables) {
  return Object.entries(variables).reduce(
    (result, [key, replacement]) => result.replaceAll(`{${key}}`, replacement),
    value,
  );
}

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [preference, setPreferenceState] = useState(readPreference);
  const [deviceLanguage, setDeviceLanguage] = useState(getDeviceLanguage);
  const language = preference === "system" ? deviceLanguage : preference;

  useEffect(() => {
    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  }, [language]);

  useEffect(() => {
    const syncDeviceLanguage = () => setDeviceLanguage(getDeviceLanguage());
    window.addEventListener("languagechange", syncDeviceLanguage);
    return () => window.removeEventListener("languagechange", syncDeviceLanguage);
  }, []);

  const value = useMemo(() => ({
    language,
    preference,
    deviceLanguage,
    setPreference(nextPreference) {
      setPreferenceState(nextPreference);
      if (nextPreference === "system") {
        window.localStorage.removeItem(STORAGE_KEY);
      } else {
        window.localStorage.setItem(STORAGE_KEY, nextPreference);
      }
    },
    t(key, variables = {}) {
      const value = lookup(messages[language], key) ?? lookup(messages.zh, key) ?? key;
      return interpolate(value, variables);
    },
  }), [deviceLanguage, language, preference]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
